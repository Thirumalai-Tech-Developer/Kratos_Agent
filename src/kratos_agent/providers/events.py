"""Canonical event normalization engine for multi-provider execution fabric."""
from __future__ import annotations

import logging
import re
import time
import uuid
from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any

from kratos_agent.core.event_bus import event_bus
from kratos_agent.core.runtime_contracts import EventKind, RuntimeEvent

logger = logging.getLogger(__name__)


class EventSeverity(str, Enum):
    DEBUG = "debug"
    INFO = "info"
    WARNING = "warning"
    ERROR = "error"
    CRITICAL = "critical"


class CanonicalEventType(str, Enum):
    # Lifecycle
    TASK_STARTED = "task.started"
    TASK_PROGRESS = "task.progress"
    TASK_COMPLETED = "task.completed"
    TASK_FAILED = "task.failed"
    TASK_CANCELLED = "task.cancelled"
    TASK_INTERRUPTED = "task.interrupted"

    # Streaming Tokens
    TOKEN_DELTA = "token.delta"
    ASSISTANT_DELTA = "token.delta"
    REASONING_DELTA = "reasoning.delta"
    ASSISTANT_THOUGHT = "reasoning.delta"
    MESSAGE_COMPLETE = "message.complete"

    # Tools
    TOOL_CALL_STARTED = "tool.started"
    TOOL_CALL_PROGRESS = "tool.progress"
    TOOL_CALL_COMPLETED = "tool.completed"
    TOOL_CALL_FAILED = "tool.failed"

    # Filesystem & Shell
    FILE_MODIFIED = "file.modified"
    COMMAND_OUTPUT = "command.output"

    # System & Provider
    PROVIDER_SELECTED = "provider.selected"
    PROVIDER_FALLBACK = "provider.fallback"
    PROVIDER_DISCONNECTED = "provider.disconnected"
    APPROVAL_REQUESTED = "approval.requested"
    APPROVAL_RESOLVED = "approval.resolved"
    VERIFICATION_STARTED = "verification.started"
    VERIFICATION_RESULT = "verification.result"


# Regex patterns for stripping sensitive tokens from narration and logs (§38)
_SECRET_PATTERNS = [
    re.compile(r"""(?:api[_-]?key|secret|token|password|auth|bearer)[\s:=]+['"]?([a-zA-Z0-9_\-\.]{8,})['"]?""", re.IGNORECASE),
    re.compile(r'sk-[a-zA-Z0-9]{20,}', re.IGNORECASE),
    re.compile(r'ghp_[a-zA-Z0-9]{20,}', re.IGNORECASE),
    re.compile(r'AIza[0-9A-Za-z-_]{20,}', re.IGNORECASE),
]


def redact_secrets(text: str) -> str:
    """Scrub potential credentials and tokens from user-facing logs and voice narration."""
    if not text:
        return ""
    sanitized = text
    for pattern in _SECRET_PATTERNS:
        sanitized = pattern.sub("[REDACTED]", sanitized)
    return sanitized


@dataclass
class AgentEvent:
    """Canonical, normalized event generated by any provider or internal subsystem."""
    task_id: str
    session_id: str
    provider: str
    event_type: CanonicalEventType
    payload: dict[str, Any] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)
    severity: EventSeverity = EventSeverity.INFO
    event_id: str = field(default_factory=lambda: uuid.uuid4().hex)

    # Voice & Live Narration (§31, §32)
    voice_narratable: bool = False
    voice_text: str | None = None
    voice_priority: int = 0  # Higher = higher priority for voice delivery

    def __init__(
        self,
        task_id: str,
        session_id: str,
        provider: str,
        event_type: CanonicalEventType,
        payload: dict[str, Any] | None = None,
        timestamp: float | None = None,
        severity: EventSeverity = EventSeverity.INFO,
        event_id: str | None = None,
        voice_narratable: bool = False,
        voice_text: str | None = None,
        voice_priority: int = 0,
        narratable: bool | None = None,
        **kwargs: Any,
    ) -> None:
        self.task_id = task_id
        self.session_id = session_id
        self.provider = provider
        self.event_type = event_type
        self.payload = payload or {}
        self.timestamp = timestamp if timestamp is not None else time.time()
        self.severity = severity
        self.event_id = event_id or uuid.uuid4().hex
        if narratable is not None:
            self.voice_narratable = narratable
        elif voice_narratable:
            self.voice_narratable = True
        else:
            self.voice_narratable = bool(voice_text)
        self.voice_text = voice_text
        self.voice_priority = voice_priority

    @property
    def narratable(self) -> bool:
        return self.voice_narratable

    def to_dict(self) -> dict[str, Any]:
        return {
            "event_id": self.event_id,
            "task_id": self.task_id,
            "session_id": self.session_id,
            "provider": self.provider,
            "event_type": self.event_type.value,
            "payload": self.payload,
            "timestamp": self.timestamp,
            "severity": self.severity.value,
            "voice_narratable": self.voice_narratable,
            "voice_text": redact_secrets(self.voice_text or "") if self.voice_text else "",
            "voice_priority": self.voice_priority,
        }

    def emit(self) -> None:
        """Publish canonical event to global Kratos EventBus as a RuntimeEvent."""
        # Convert canonical event to core RuntimeEvent for backwards compatibility
        kind_map: dict[CanonicalEventType, EventKind] = {
            CanonicalEventType.TASK_STARTED: EventKind.TASK_STARTED,
            CanonicalEventType.TASK_COMPLETED: EventKind.TASK_COMPLETED,
            CanonicalEventType.TASK_FAILED: EventKind.TASK_FAILED,
            CanonicalEventType.TOKEN_DELTA: EventKind.MODEL_CHUNK,
            CanonicalEventType.REASONING_DELTA: EventKind.MODEL_THINKING,
            CanonicalEventType.MESSAGE_COMPLETE: EventKind.MODEL_RESPONSE,
            CanonicalEventType.TOOL_CALL_STARTED: EventKind.TOOL_CALL_STARTED,
            CanonicalEventType.TOOL_CALL_COMPLETED: EventKind.TOOL_COMPLETED,
            CanonicalEventType.TOOL_CALL_FAILED: EventKind.TOOL_FAILED,
            CanonicalEventType.FILE_MODIFIED: EventKind.FILE_MODIFIED,
            CanonicalEventType.COMMAND_OUTPUT: EventKind.COMMAND_COMPLETED,
            CanonicalEventType.VERIFICATION_STARTED: EventKind.VERIFICATION_STARTED,
            CanonicalEventType.VERIFICATION_RESULT: EventKind.VERIFICATION_COMPLETED,
        }

        rk = kind_map.get(self.event_type, EventKind.TASK_UPDATED)
        runtime_event = RuntimeEvent(
            kind=rk,
            payload={
                **self.payload,
                "canonical_type": self.event_type.value,
                "provider": self.provider,
                "task_id": self.task_id,
                "session_id": self.session_id,
                "voice_text": redact_secrets(self.voice_text) if self.voice_text else None,
            },
            turn_id=self.task_id,
            timestamp=self.timestamp,
        )
        event_bus.publish(runtime_event)


# Event listener registry for providers
_event_listeners: list[Any] = []


def register_event_listener(listener: Any) -> None:
    if listener not in _event_listeners:
        _event_listeners.append(listener)


def publish_agent_event(event: AgentEvent) -> None:
    """Dispatches canonical AgentEvent to registered listeners and global EventBus."""
    event.emit()
    for listener in _event_listeners:
        try:
            listener(event)
        except Exception as exc:
            logger.debug("Error in event listener: %s", exc)
