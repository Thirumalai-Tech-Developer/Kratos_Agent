"""Regenerate a source inventory; source presence never implies runtime validation."""
from __future__ import annotations
import hashlib
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "services/omniroute"


def route(path: str) -> str:
    parts = path.split("/")[2:-1]
    return "/" + "/".join(p for p in parts if not p.startswith("("))


def inventory() -> dict:
    manifest = json.loads((ROOT / "integration/omniroute-source.json").read_text())
    entries = []
    modified, missing = [], []
    for item in manifest["files"]:
        name = item["path"]
        path = SOURCE / name
        if not path.is_file():
            missing.append(name)
            continue
        if hashlib.sha256(path.read_bytes()).hexdigest() != item["sha256"]:
            modified.append(name)
        category = None
        url = None
        if name.startswith("src/app/") and name.endswith("/page.tsx"):
            category, url = "page", route(name)
        elif name.startswith("src/app/") and name.endswith("/route.ts"):
            category, url = "api", route(name)
        else:
            for prefix, kind in [
                ("open-sse/executors/", "provider-executor"),
                ("open-sse/config/providers/", "provider-definition"),
                ("open-sse/services/compression/", "compression"),
                ("open-sse/mcp-server/tools/", "mcp-tool"),
                ("src/lib/db/", "persistent-store"),
                ("src/lib/plugins/", "plugin"),
                ("src/lib/skills/", "skill"),
                ("src/lib/acp/", "agent-protocol"),
                ("src/lib/cloudAgent/", "cloud-agent"),
                ("src/lib/conductor/", "conductor"),
                ("src/lib/a2a/", "agent-protocol"),
                ("bin/", "cli"),
                ("electron/", "desktop"),
            ]:
                if name.startswith(prefix) and name.endswith((".ts", ".tsx", ".js", ".mjs", ".sql")):
                    category = kind
                    break
        if category:
            entries.append({"category": category, "source": name, "route": url,
                            "implementation": "included", "validation": "pending"})
    settings = (SOURCE / "src/shared/constants/featureFlagDefinitions.ts").read_text(encoding="utf-8")
    flags = sorted(set(re.findall(r'key:\s*"([A-Z][A-Z0-9_]+)"', settings)))
    return {"scope": "Current modified OmniRoute working snapshot; future roadmap excluded",
            "source_commit": manifest["source_commit"], "imported_files": len(manifest["files"]),
            "missing_files": missing, "integration_modified_files": modified,
            "counts": dict(sorted(Counter(e["category"] for e in entries).items())),
            "feature_flags": flags, "entries": entries}


if __name__ == "__main__":
    data = inventory()
    (ROOT / "integration/feature-ledger.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    rows = ["# Imported feature inventory", "", "Generated by `scripts/integration/feature_ledger.py`. Runtime validation is tracked separately; a source file is not proof of a working integration.", "", "| Category | Items |", "| --- | ---: |"]
    rows += [f"| {category} | {count} |" for category, count in data["counts"].items()]
    rows += ["", "The machine-readable ledger contains every matching source path and application route.", "", f"Imported source files: {data['imported_files']}. Missing imported files: {len(data['missing_files'])}."]
    (ROOT / "integration/FEATURES.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(json.dumps({"counts": data["counts"], "missing": data["missing_files"]}, indent=2))
